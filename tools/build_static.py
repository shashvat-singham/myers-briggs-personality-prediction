#!/usr/bin/env python
"""Render the Jinja templates into a static site for Netlify.

One set of templates serves both deployments: Flask renders them per request,
and this script pre-renders them into `dist/` for the CDN. That avoids the
usual drift between "the real site" and "the static copy".

In the static build there is no Python at request time, so anything dynamic --
the prediction result, the history table -- is left as an empty shell and filled
in by static/javascript/predictor.js, which calls the backend through the
`/api/*` proxy configured in netlify.toml.

Usage:
    python tools/build_static.py [--out dist] [--backend-url https://...]

Environment:
    BACKEND_URL     Backend origin used for the proxy rules (required for a
                    working deploy; the build warns but succeeds without it so
                    preview builds are still inspectable).
    COMMIT_REF      Provided by Netlify; recorded in the build banner.
"""
import argparse
import json
import os
import shutil
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEMPLATES_DIR = os.path.join(ROOT, "templates")
STATIC_DIR = os.path.join(ROOT, "static")

# (template, output path). response.html and history.html render in their
# "no data yet" state and hydrate client-side.
PAGES = (
    ("index.html", "index.html"),
    ("response.html", "response.html"),
    ("history.html", "history.html"),
    ("analysis.html", "analysis.html"),
    ("methodology.html", "methodology.html"),
    ("about.html", "about.html"),
    ("error.html", "404.html"),
)


def url_for(endpoint, **values):
    """Stand-in for Flask's url_for, resolving to CDN-relative paths."""
    if endpoint == "static":
        return "/static/%s" % values.get("filename", "").lstrip("/")
    if endpoint in ("web.index", "index"):
        return "/"
    # `web.history` -> /history
    return "/%s" % endpoint.split(".")[-1]


def build_env():
    try:
        from jinja2 import Environment, FileSystemLoader, select_autoescape
    except ImportError:
        sys.stderr.write(
            "jinja2 is required to build the static site.\n"
            "  pip install jinja2==3.1.4\n"
        )
        raise SystemExit(2)

    env = Environment(
        loader=FileSystemLoader(TEMPLATES_DIR),
        autoescape=select_autoescape(["html", "xml"]),
    )
    env.globals["url_for"] = url_for
    return env


def render(env, out_dir, context):
    written = []
    for template_name, output_name in PAGES:
        path = os.path.join(TEMPLATES_DIR, template_name)
        if not os.path.exists(path):
            sys.stderr.write("skipping missing template: %s\n" % template_name)
            continue
        html = env.get_template(template_name).render(**context)
        target = os.path.join(out_dir, output_name)
        with open(target, "w", encoding="utf-8") as handle:
            handle.write(html)
        written.append(output_name)
    return written


def copy_static(out_dir):
    target = os.path.join(out_dir, "static")
    if os.path.isdir(target):
        shutil.rmtree(target)
    shutil.copytree(STATIC_DIR, target)
    return target


def write_redirects(out_dir, backend_url):
    """Emit _redirects with the backend origin substituted in.

    netlify.toml cannot interpolate environment variables into redirect
    targets, and _redirects wins over netlify.toml, so the real rules are
    generated here at build time.
    """
    lines = [
        "# Generated by tools/build_static.py -- do not edit by hand.",
        "# Rules here take precedence over netlify.toml.",
        "",
    ]
    if backend_url:
        origin = backend_url.rstrip("/")
        lines += [
            "# Proxy API traffic to the container backend (same-origin for the browser).",
            "/api/*        %s/api/:splat        200!" % origin,
            "/response     %s/response          200!" % origin,
            "/healthz      %s/healthz           200!" % origin,
            "",
        ]
    else:
        lines += [
            "# BACKEND_URL was not set at build time: no API proxy is configured.",
            "# The site renders, but predictions will fail until it is set.",
            "",
        ]

    lines += [
        "# Clean URLs for the pre-rendered pages.",
        "/history      /history.html       200",
        "/analysis     /analysis.html      200",
        "/methodology  /methodology.html   200",
        "/about        /about.html         200",
        "",
    ]

    path = os.path.join(out_dir, "_redirects")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    return path


def write_frontend_config(out_dir, backend_url, commit_ref):
    """Runtime config for the browser.

    A generated JS file rather than an inlined constant, so the same
    predictor.js is served by Flask and by Netlify.
    """
    config = {
        # Relative by default: requests go to the Netlify origin and are
        # proxied, which keeps CSP connect-src at 'self'.
        "apiBase": "/api/v1",
        "backendConfigured": bool(backend_url),
        "buildTime": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "commit": (commit_ref or "")[:12],
        "static": True,
    }
    js_dir = os.path.join(out_dir, "static", "javascript")
    if not os.path.isdir(js_dir):
        os.makedirs(js_dir)
    path = os.path.join(js_dir, "app-config.js")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(
            "// Generated by tools/build_static.py\n"
            "window.MBPP_CONFIG = %s;\n" % json.dumps(config, indent=2)
        )
    return path


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=os.path.join(ROOT, "dist"))
    parser.add_argument("--backend-url", default=os.environ.get("BACKEND_URL", ""))
    args = parser.parse_args(argv)

    out_dir = os.path.abspath(args.out)
    backend_url = args.backend_url.strip()

    if os.path.isdir(out_dir):
        shutil.rmtree(out_dir)
    os.makedirs(out_dir)

    env = build_env()
    context = {
        # Rendered without a request: the dynamic regions stay empty and
        # predictor.js hydrates them.
        "is_static": True,
        "name": None,
        "string": None,
        "axes": None,
        "items": [],
        "stats": None,
        "storage_available": True,
        "status_code": 404,
        "message": "That page does not exist.",
    }

    pages = render(env, out_dir, context)
    copy_static(out_dir)
    write_redirects(out_dir, backend_url)
    write_frontend_config(out_dir, backend_url, os.environ.get("COMMIT_REF", ""))

    print("built %d pages into %s" % (len(pages), out_dir))
    for page in pages:
        print("  - %s" % page)
    if backend_url:
        print("api proxy -> %s" % backend_url)
    else:
        print(
            "WARNING: BACKEND_URL is unset. The static site will load but "
            "predictions will return 404 until you set it in Netlify's "
            "environment variables and redeploy."
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
